class grGimmickWarpZone : public Ground {
public:
    char pad40[0x110];
    unsigned char* data;
    void setInitializeFlag();
};

void grGimmickWarpZone::setInitializeFlag() {
    if (!g_stTriggerMng->getTriggerFlag((stTriggerData*)(data + 0x7c), true)) {
        if (data[0x7e] & 1) {
            setValid(0);
        }
    } else {
        if (!(data[0x7e] & 1)) {
            setValid(0);
        }
    }
}
